"""Human-reviewable views of the audit chain.

The JSONL chain stays the record of truth. Everything here is derived from it and
stamped with the chain's verification result at generation time, so a reviewer can
read a clean report and still prove it matches an intact chain:

  - render_report(): fixed-column text review log with a header and summary.
    The last line carries a SHA-256 of everything above it, so edits to a saved
    report are detectable with `palisade audit check-report <file>`.
  - anchor(): the current head hash with a timestamp, for storing off the machine.
    If the chain is later rewritten, it will no longer reach an anchored head hash.
"""
from __future__ import annotations

import getpass
import json
import os
import re
import time
from collections import Counter
from pathlib import Path
from typing import Any, Iterable

from . import sha256_text, __version__
from .audit import AuditLog

REPORT_HASH_PREFIX = "Report SHA-256 (all lines above): "
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")

DECISION_LABEL = {
    "answered": "answered",
    "flagged": "FLAGGED",
    "blocked_input": "BLOCKED-INPUT",
    "blocked_output": "BLOCKED-OUTPUT",
    "rejected": "REJECTED",
    "error": "ERROR-CLOSED",
}


def _who() -> str:
    try:
        return f"{getpass.getuser()} (uid {os.getuid()})" if hasattr(os, "getuid") else getpass.getuser()
    except Exception:
        return "unknown"


def _score(verdicts: list[dict], stage: str) -> str:
    for v in verdicts:
        if v.get("stage") == stage:
            return f"{float(v.get('p_violation', 0)):.2f}"
    return "  -  "


def _cats(verdicts: list[dict]) -> str:
    names = sorted({c for v in verdicts for c in (v.get("categories") or [])})
    return ",".join(names) if names else "-"


def _clean(text: str, limit: int = 500) -> str:
    text = _CTRL.sub(" ", text or "").replace("\n", " ⏎ ")
    return text if len(text) <= limit else text[:limit] + " …[truncated]"


def render_report(log: AuditLog, *, decision: str | None = None,
                  include_content: bool = False, manifest_hash: str = "",
                  generated_by: str | None = None) -> str:
    v = log.verify()
    records: Iterable[dict] = log.all_records()
    if decision:
        if decision == "blocked":
            records = [r for r in records if str(r.get("decision", "")).startswith("blocked")]
        else:
            records = [r for r in records if r.get("decision") == decision]
    records = list(records)

    status = (f"INTACT ({v['records']} records verified)" if v["intact"]
              else f"BROKEN at record #{v['first_break']['seq']} in {v['first_break']['file']} "
                   f"({v['records']} records scanned) - TREAT THIS LOG AS UNTRUSTED")
    rule = "=" * 118
    lines = [
        "PALISADE AUDIT REVIEW LOG",
        f"Generated:      {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}",
        f"Generated by:   {generated_by or _who()}",
        f"Palisade:       {__version__}",
        f"Chain status:   {status}",
        f"Head hash:      {v['head_hash']}",
        f"Manifest hash:  {manifest_hash or 'n/a'}",
        f"Filter:         {decision or 'all decisions'}",
        f"Content:        {'included where retained' if include_content else 'hashes only'}",
        rule,
        f"{'SEQ':>6}  {'TIME (UTC)':<20}  {'DECISION':<15}  {'IN':>5}  {'OUT':>5}  "
        f"{'CATEGORIES':<24}  {'POLICY':<22}  RECORD HASH",
        f"{'-'*6}  {'-'*20}  {'-'*15}  {'-'*5}  {'-'*5}  {'-'*24}  {'-'*22}  {'-'*12}",
    ]
    counts: Counter = Counter()
    for r in records:
        d = r.get("decision", "?")
        counts[d] += 1
        verdicts = r.get("verdicts") or []
        lines.append(
            f"{r.get('seq', 0):>6}  {r.get('ts', ''):<20}  {DECISION_LABEL.get(d, d):<15}  "
            f"{_score(verdicts, 'input'):>5}  {_score(verdicts, 'output'):>5}  "
            f"{_cats(verdicts)[:24]:<24}  {str(r.get('policy_version', ''))[:22]:<22}  "
            f"{str(r.get('hash', ''))[:12]}")
        h = r.get("harness") or {}
        notes = [h.get("reason")] if h.get("reason") else []
        if h.get("input_cleaned"):
            notes.append("input cleaned: " + ", ".join(f"{k}={v}" for k, v in h["input_cleaned"].items()))
        if h.get("output_cleaned"):
            notes.append("output cleaned: " + ", ".join(f"{k}={v}" for k, v in h["output_cleaned"].items()))
        notes += [v["note"] for v in verdicts if v.get("note")]
        if h.get("source"):
            notes.append(f"source: {h['source']}")
        if notes:
            lines.append(f"{'':>8}harness:  {_clean('; '.join(notes), 300)}")
        if include_content and (r.get("prompt") or r.get("response")):
            lines.append(f"{'':>8}prompt:   {_clean(r.get('prompt') or '')}")
            lines.append(f"{'':>8}response: {_clean(r.get('response') or '')}")
    if not records:
        lines.append("  (no records match this filter)")
    lines += [
        rule,
        "Summary:        " + "  ".join(f"{DECISION_LABEL.get(k, k)} {counts.get(k, 0)}"
                                      for k in ("answered", "flagged", "blocked_input", "blocked_output",
                                                "rejected", "error")),
        f"Records listed: {len(records)}",
    ]
    body = "\n".join(lines) + "\n"
    return body + REPORT_HASH_PREFIX + sha256_text(body) + "\n"


def check_report(text: str) -> dict[str, Any]:
    """Confirm a saved report has not been edited since generation."""
    idx = text.rfind(REPORT_HASH_PREFIX)
    if idx < 0:
        return {"valid": False, "reason": "no report hash line found"}
    body = text[:idx]
    recorded = text[idx + len(REPORT_HASH_PREFIX):].strip()
    actual = sha256_text(body)
    return {"valid": recorded == actual, "recorded": recorded, "actual": actual}


def anchor(log: AuditLog, manifest_hash: str = "") -> dict[str, Any]:
    v = log.verify()
    return {
        "type": "palisade-audit-anchor",
        "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "records": v["records"],
        "head_hash": v["head_hash"],
        "chain_intact": v["intact"],
        "manifest_hash": manifest_hash,
        "note": "Store this outside the machine. A later chain that does not pass through "
                "this head hash at this record count has been rewritten.",
    }


def anchor_text(a: dict[str, Any]) -> str:
    return json.dumps(a, indent=2) + "\n"


def check_anchor(log: AuditLog, a: dict[str, Any]) -> dict[str, Any]:
    """Confirm the current chain still passes through an anchored head hash.

    Recomputes every hash from the start up to the anchored record rather than
    trusting stored hash fields, so it catches both kinds of tampering:
      - edits that leave stored hashes alone (recomputation disagrees), and
      - rewrites that recompute every hash (the head no longer matches the anchor).
    """
    from .audit import GENESIS
    n, want = int(a.get("records", 0)), a.get("head_hash", "")
    warn = [] if a.get("chain_intact", True) else [
        "this anchor was taken while the chain was already broken; it only proves "
        "what the chain looked like at that time"]
    if n == 0:
        return {"valid": True, "reason": "anchor taken on an empty chain", "warnings": warn}
    prev, seq = GENESIS, 0
    for rec in log.all_records():
        seq += 1
        recomputed = AuditLog.compute_hash(prev, rec)
        if rec.get("seq") != seq or rec.get("prev_hash") != prev or recomputed != rec.get("hash"):
            return {"valid": False, "seq": seq, "warnings": warn,
                    "reason": f"chain does not recompute at record #{seq}: history was altered"}
        prev = recomputed
        if seq == n:
            ok = recomputed == want
            return {"valid": ok, "seq": n, "warnings": warn,
                    "reason": "chain passes through the anchored head" if ok
                    else "record at the anchored position hashes differently: history was rewritten"}
    return {"valid": False, "seq": n, "warnings": warn,
            "reason": "chain is shorter than the anchor: records were removed"}
